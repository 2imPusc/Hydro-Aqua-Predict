"""Write docs/data-manifest.md: every local data file with size and sha256.

data/ is gitignored, so this manifest is the tracked record of what a working
checkout needs and lets a fresh machine verify a restored copy.

    python scripts/data_manifest.py            # regenerate
    python scripts/data_manifest.py --check    # verify local data/ against it
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from core import paths  # noqa: E402

MANIFEST = paths.PROJECT_ROOT / "docs" / "data-manifest.md"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def scan() -> list[tuple[str, int, str]]:
    rows = []
    for path in sorted(paths.DATA_DIR.rglob("*")):
        if path.is_file():
            rows.append((path.relative_to(paths.DATA_DIR).as_posix(), path.stat().st_size, sha256(path)))
    return rows


def write(rows: list[tuple[str, int, str]]) -> None:
    lines = [
        "# Data manifest",
        "",
        "Generated by `python scripts/data_manifest.py`. `data/` is gitignored; see",
        "[data-policy.md](data-policy.md) for what each group is and where it comes from.",
        "",
        "| File (under `data/`) | Bytes | sha256 (first 16) |",
        "| --- | ---: | --- |",
    ]
    lines += [f"| `{name}` | {size:,} | `{digest[:16]}` |" for name, size, digest in rows]
    lines += ["", f"Total: {len(rows)} files, {sum(r[1] for r in rows) / 1e6:,.1f} MB", ""]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")


def check(rows: list[tuple[str, int, str]]) -> int:
    expected = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if line.startswith("| `"):
            cells = [c.strip().strip("`") for c in line.strip("|").split("|")]
            expected[cells[0]] = cells[2]
    actual = {name: digest[:16] for name, _, digest in rows}
    missing = sorted(set(expected) - set(actual))
    changed = sorted(n for n in expected.keys() & actual.keys() if expected[n] != actual[n])
    for name in missing:
        print(f"MISSING  {name}")
    for name in changed:
        print(f"CHANGED  {name}")
    print(f"{len(expected) - len(missing) - len(changed)}/{len(expected)} files match")
    return 1 if missing else 0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = scan()
    if args.check:
        sys.exit(check(rows))
    write(rows)
    print(f"wrote {MANIFEST} ({len(rows)} files)")


if __name__ == "__main__":
    main()
